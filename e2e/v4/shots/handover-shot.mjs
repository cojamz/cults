import { launchBrowser } from '../lib/browser.mjs';
import { handoverSave } from '/home/user/patrons/e2e/v4/lib/handover-save.mjs';
import { seedSave } from '/home/user/patrons/e2e/v4/lib/seed.mjs';
const out = process.argv[2];
const b = await launchBrowser({ executablePath: '/opt/pw-browsers/chromium' });
const ctx = await b.newContext({ viewport: { width: 1270, height: 700 }, deviceScaleFactor: 2 });
const page = await ctx.newPage();
page.on('pageerror', e => console.log('pageerror', e.message));
const save = handoverSave();
await seedSave(page, save);
await page.goto('http://localhost:5291/?intro=0');
await page.waitForSelector('[data-home="resume"]', { timeout: 60000 });
await page.click('[data-home="resume"]');
await page.waitForSelector('.gift-card', { timeout: 60000 });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/1-pick-a-member.png` });
const m = await page.$('.gift-card .gc-row[data-row="1"] .gc-member');
await m.click();
await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/2-then-a-rival.png` });
const card = await page.$('.gift-card');
await card.screenshot({ path: `${out}/2-card-close.png` });
await b.close();
